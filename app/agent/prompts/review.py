"""Reviewer 第二阶段的 prompt（详细设计 14.1 的"结构化模型审查"）。

## 它回答的是第一阶段**答不了**的那类问题

第一阶段是代码，判的是"有没有引用"；这一阶段判的是"**引用的那些够不够**"
——那是语义。「一条 FACT 挂着三条引用」与「那三条支持这句话」是两个问题，
前者代码能判，后者只有模型能判。14.1 把这四条列得很清楚：

| 14.1 的原文 | 对应的输出字段 |
|---|---|
| 是否回答问题 | `question_answered` |
| 证据是否足够 | `evidence_sufficient` |
| 推断是否越界 | `inference_within_bounds` |
| 限制是否清楚 | `limitations_clear` |
| 应补哪类证据 | `retry_target` + `retry_reason` |

## 措辞纪律：**四条默认都是"通过"**

输出里的四个布尔**默认 `true`**，只有确实看出问题时才填 `false`。
这条必须写在 prompt 里，因为模型的默认倾向是"找点毛病显得尽责"——
而这里每一次误报的代价不是一条日志，是**一次真花钱的 Tool 重试**
（14.3 明写"不得以文风不够好为由触发"），或者一条本该发布的答案被拦下。

同理，`retry_target` **只在"重跑某个工具没用"时才填**：
14.3 对它的定义是"证据缺口需要一个新的下钻方向才能补齐"。
"某条 SQL 写错了"不属于这一类——那有它自己的路径。

## 它看不到 `evd_`

证据在这里也是**编号**（`[E1]`），与 `analysis` 那条链路一致：
26 位 Base32 的原始 id 让模型逐字抄一遍，出错率高得没有道理，
而抄错一个字符的后果是引用指向不存在的证据。
"""

from __future__ import annotations

from typing import Final

from app.agent.prompts.base import PromptTemplate

REVIEW_PROMPT: Final[PromptTemplate] = PromptTemplate(
    name="review_second_stage",
    version="1.0.0",
    template="""\
你是企业数据分析的**发布前审查员**。下面是一份已经写好的答案，以及它引用的
全部证据。请判断这份答案能不能交给用户。

用户问题：{question}

待审的答案：
{answer}

该答案引用的证据（编号即答案里的引用标识）：
{evidence}

请逐条判断（**默认都是"通过"，只有确实看出问题才判不通过**）：

1. question_answered：**回答的是用户问的那件事吗**？问 A 答 B、只答了一半、
   用一段背景介绍代替回答，都算没回答。
2. evidence_sufficient：**引用的证据够不够支持这句话**？注意这里判的不是
   "有没有引用"（那已经查过了），而是"引用的那些够不够"——
   例如只召回了一张 80 行明细表里的 3 行，却据此给出整表合计。
3. inference_within_bounds：**推断有没有越过证据**？把相关性说成因果、
   把个别说成普遍、把"某个月"说成"全年趋势"，都算越界。
4. limitations_clear：**限制说清楚了吗**？语料里没有、某一步没跑到、
   时点没给——这些必须在答案里说明，而不是留给读者去猜。

另外两个字段：

- retry_target：**只在这类情形才填**——"缺的是一整类信息，重跑原来那个
  工具没有用，必须换一条取证路径"。可选值有 sql / rag / expand，
  并请在 retry_reason 里说清要补什么。**不要写具体 SQL**。
  如果问题只是"某个数查错了"，那不是这一类，留空即可。
- clarification_question：**需要用户先定口径 / 时间 / 范围时**才填，
  而且要写成**用户能直接回答的一句问话**（"你要看的是哪个季度？"），
  不要写"请提供更多信息"这种他答不上来的话。

**四个判断默认都填 true。** 每判一个 false 都可能触发一次真花钱的重新取证，
或让一条本来可以发布的答案被拦下——所以只在确实看出问题时才判不通过。""",
)

__all__ = ["REVIEW_PROMPT"]
