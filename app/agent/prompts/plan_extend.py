"""`plan_extend` 的 prompt（详细设计 8.5 的「PlanExtend 与 Planner 的关系」）。

## 它只回答一个问题：**接下来该补查什么**

与 `supervisor` 那条（"这个问题该用哪几路"）不同，这一条的输入里已经有
**跑过的步骤和拿到的证据**，问的是"还差什么、要往哪个方向再走一步"。
14.3 把它的触发条件说得很窄：

> 当审查发现的问题不是"某个查询错了"，而是"缺少一整类信息"时，
> 重跑同一个工具不会有用，必须新增步骤。

所以这里既不该写 SQL，也不该复述已经查到的东西——它出的是**方向**。
详设 8.5 的原文是"PlanExtend 决定具体步骤，而不是由 Reviewer 直接指定 SQL"，
而"具体步骤"在本实现里就是一句 `objective` 加一个工具名。

## 允许它说"没什么可补的"

`steps` 可以为空，而且**不填比硬凑好**：这一步是增强，不是必经路径，
一次凭空的"再查查别的"会真花掉两个工具调用的时间，还占掉一次演进预算。
6.6.3 也明写演进失败要按 SUFFICIENT 收敛，而不是报错。

## 措辞纪律：**不要重复已经做过的事**

去重由代码按 `(工具, 归一化目标)` 判（6.6.3 第 6 条），但那只是最后一道闸；
让模型自己避开已跑过的方向，比事后丢弃便宜——被丢掉的那一步同时也会
占掉一次演进预算的校验名额，而"提了三步、只活下来一步"在产物上
只留下一行 `plan_extend_rejected`。
"""

from __future__ import annotations

from typing import Final

from app.agent.prompts.base import PromptTemplate

PLAN_EXTEND_PROMPT: Final[PromptTemplate] = PromptTemplate(
    name="plan_extend",
    version="1.0.0",
    template="""\
你是企业数据分析的**取证规划员**。一个分析任务已经跑了一部分，审查认为
**缺少一整类信息**——重跑原来那个工具没有用，必须换一条取证路径。
请你决定接下来该补查什么。

用户问题：{question}

已经执行的步骤：
{plan}

已经拿到的证据：
{evidence}

要补的理由（来自上一轮判定或审查结论）：
{reason}

可用的工具只有两个：

- `sql_query`：查业务数据库里的数值（销售额、订单量、库存、退货金额等，
  可按区域 / 渠道 / 产品线 / 时间拆解）。
- `rag_retrieve`：查企业制度与报告知识库里的**文字**（指标口径、政策规定、
  报告里的解释与结论）。

请提出 **1 到 3 个**新的分析步骤，每个步骤给出：

- `objective`：这一步要查清什么，写成一句能判断做没做到的话。
- `tool`：只能填 `sql_query` 或 `rag_retrieve`。

另外填一个 `reason`：**为什么这几步能补上缺的那类信息**。

三条约束：

1. **不要重复已经执行过的方向**。目标相同、只是换个说法，也算重复。
2. **只补缺的那一类**。已经查过数据库并且拿到了数，就不要再提一条 SQL；
   审查说"缺一整类信息"，通常指的是**另一路**还没查，或者需要换一个维度拆解。
3. **没什么可补的就留空**。`steps` 可以是空数组——那比凑几步强，
   因为每一步都要真花钱、真花时间。宁可说"补不了"，也不要提一条
   方向含糊、查完也不知道算不算做到的步骤。""",
)

