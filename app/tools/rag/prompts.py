"""RAG 检索侧的 prompt 模板（详细设计 11.7 第 2 步）。

**只有一条**：Query Rewrite。检索本身是确定性的（标量过滤 + 双路召回 + RRF），
这里不需要第二个模型调用——11.7 的第 6 步（重排）是**另一个模型**的事，
且按 TBC-04 后置。

## 「必须保留实体和时间」是校验规则，不是客套话

11.7 第 2 步原文：*Query Rewrite 生成 1 至 3 个等价短查询，**必须保留实体和时间***。
这条得由代码保证，写进 prompt 只是降低了它被违反的概率——
模型把「2025 年华东 Q3」改写成「三季度区域业绩」时，检索仍然跑得通、
仍然返回一堆结果，**只是不再是我们问的那件事**，没有任何报错。
因此 `retriever.py` 会把改写结果与原问题里的数字/年份逐一比对，
丢掉丢了实体的那些（见 `retriever._keeps_entities`）。

## 与 SQL prompt 同样的两条纪律

- **模板里不写 JSON 格式说明**：那是服务方的协议要求，由
  `model_gateway.build_json_contract` 依 `QueryRewrite` 的 Schema 统一追加。
- **改动模板必须升 `version`**：`prompt_version` 随调用记录落库，
  改文本不升版本会让历史记录指向两段不同的文本。
"""

from __future__ import annotations

from typing import Final

from app.agent.prompts.base import PromptTemplate

#: Query Rewrite 模板。
#:
#: 三条要求的理由：
#: - **术语用制度里的写法**：语料里写「渠道折扣」「净销售额」「归口管理部门」，
#:   用户问「打折政策」「收入」「谁管」时，稀疏路一个 token 都对不上
#:   （11.6.2 的业务词典收的是制度侧的词形）。改写就是把口语映射到词表里的词。
#: - **不要解释、不要回答**：模型很容易顺手把问题答了，而那条"答案"
#:   既没进检索也没进证据，只会浪费 token 并让改写偏离原问题。
#: - **保持简洁**：改写的目的是让稀疏路能命中，长句会被切成更多 token，
#:   反而稀释掉真正有区分度的那几个。
QUERY_REWRITE_PROMPT: Final[PromptTemplate] = PromptTemplate(
    name="rag_query_rewrite",
    version="1.0.0",
    template="""\
你是一名检索助手，负责把用户的业务问题改写成便于在企业知识库中检索的短查询。

用户问题：{question}
分析目标：{objective}

要求：
- 生成 1 到 3 条**等价**的短查询，每条不超过 30 个字；
- **必须保留原问题里的全部实体与时间**：区域名、渠道名、产品线、制度名称、
  年份与季度一个都不能少，也不能换成年份以外的表述；
- 使用企业内部文件的常见说法（例如「渠道折扣」「净销售额」「归口管理部门」
  「目标达成率」），把口语化的说法替换成这些术语；
- 只输出查询本身，不要解释、不要回答问题、不要添加原问题里没有的数字或结论；
- 多条查询之间应当是**不同角度的表述**，不是把同一句话换个标点。""",
)


__all__ = ["QUERY_REWRITE_PROMPT"]
